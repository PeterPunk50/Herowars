"""Generate setup_vyrath.luau: the Studio-side setup for a freshly imported Vyrath (run with studio_mcp.py luau ... Edit).
usage: python3 -I make_setup_luau.py   (reads ../boss/*.luau, writes setup_vyrath.luau next to this file)
What the generated chunk does, in the open place's Edit data model:
  1. finds the imported model (workspace.Vyrath_all2 or workspace.Vyrath), renames it Vyrath,
  2. scales it once to 0.35 (a 25-stud boss) and stands it on y 0, centred on the origin,
  3. writes ServerScriptService.VyrathBoss {Boss, BossData, BossHarness} and StarterPlayerScripts.BossHud from ../boss,
  4. checks every clip BossData asks for exists under ServerStorage.RBX_ANIMSAVES.Vyrath_all2 and returns a report."""
import os

here = os.path.dirname(os.path.abspath(__file__))
boss = os.path.join(here, '..', 'boss')
SCALE = 0.35


def long_string(src):
    level = 1
    while (']' + '=' * level + ']') in src:
        level += 1
    eq = '=' * level
    return '[' + eq + '[\n' + src + ']' + eq + ']'


src = {name: open(os.path.join(boss, file), encoding='utf8').read() for name, file in [
    ('Boss', 'Boss.luau'), ('BossData', 'BossData.luau'), ('BossHarness', 'BossHarness.server.luau'), ('BossHud', 'BossHud.client.luau')]}

chunk = '-- generated by make_setup_luau.py from vyrath-redo/boss; do not edit by hand\nlocal SRC = {\n'
chunk += ''.join(f'\t{k} = {long_string(v)},\n' for k, v in src.items())
chunk += '}\n' + f'local SCALE = {SCALE}\n' + r'''
local report = {}
local function say(...) table.insert(report, table.concat({...}, " ")) end
local model = workspace:FindFirstChild("Vyrath") or workspace:FindFirstChild("Vyrath_all2")
assert(model, "no imported Vyrath model in workspace")
model.Name = "Vyrath"
local mesh = model:FindFirstChildWhichIsA("MeshPart", true)
assert(mesh, "model has no MeshPart")
if math.abs(model:GetScale() - 1) < 1e-4 then model:ScaleTo(SCALE) end
-- world-space box of the rest mesh, so the paws stand on y 0 whatever the pivot's base rotation is
local function worldBox()
	local cf, s = mesh.CFrame, mesh.Size
	local function half(axis)
		return (math.abs(cf.RightVector[axis]) * s.X + math.abs(cf.UpVector[axis]) * s.Y + math.abs(cf.LookVector[axis]) * s.Z) / 2
	end
	local p = cf.Position
	return p, Vector3.new(half("X"), half("Y"), half("Z"))
end
local p, h = worldBox()
model:PivotTo(model:GetPivot() + Vector3.new(-p.X, -(p.Y - h.Y), -p.Z))
p, h = worldBox()
say(("model Vyrath scale=%.3f box x %.1f..%.1f y %.2f..%.1f z %.1f..%.1f"):format(model:GetScale(), p.X - h.X, p.X + h.X, p.Y - h.Y, p.Y + h.Y, p.Z - h.Z, p.Z + h.Z))
local bones, ctl = 0, model:FindFirstChildWhichIsA("AnimationController", true)
for _, d in model:GetDescendants() do if d:IsA("Bone") then bones += 1 end end
say("bones", bones, "meshId", mesh.MeshId, "anchored", tostring(mesh.Anchored), "AnimationController", tostring(ctl ~= nil))

local function put(class, name, parent, source)
	local s = parent:FindFirstChild(name)
	if s and s.ClassName ~= class then s:Destroy(); s = nil end
	s = s or Instance.new(class)
	s.Name = name
	s.Source = source
	s.Parent = parent
	return s
end
local SSS = game:GetService("ServerScriptService")
local folder = SSS:FindFirstChild("VyrathBoss") or Instance.new("Folder")
folder.Name = "VyrathBoss"; folder.Parent = SSS
put("ModuleScript", "Boss", folder, SRC.Boss)
put("ModuleScript", "BossData", folder, SRC.BossData)
put("Script", "BossHarness", folder, SRC.BossHarness)
put("LocalScript", "BossHud", game:GetService("StarterPlayer"):FindFirstChildOfClass("StarterPlayerScripts"), SRC.BossHud)
say("scripts: ServerScriptService.VyrathBoss {Boss, BossData, BossHarness}, StarterPlayerScripts.BossHud")

local D = require(folder.BossData:Clone())
local saves = game:GetService("ServerStorage"):FindFirstChild("RBX_ANIMSAVES")
saves = saves and saves:FindFirstChild("Vyrath_all2")
local missing, found = {}, 0
for _, name in D.Clips do
	local ks = saves and saves:FindFirstChild("Armature|" .. name)
	if ks and ks:IsA("KeyframeSequence") then found += 1 else table.insert(missing, name) end
end
say(("clips BossData wants %d, found %d, missing: %s"):format(#D.Clips, found, #missing > 0 and table.concat(missing, ", ") or "none"))
return table.concat(report, "\n")
'''
out = os.path.join(here, 'setup_vyrath.luau')
open(out, 'w', encoding='utf8').write(chunk)
print('wrote', out, len(chunk), 'bytes')
